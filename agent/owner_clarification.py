"""Shared policy and structured results for owner decisions in any call."""
import json

OWNER_CLARIFICATION_POLICY = '''
УНИВЕРСАЛЬНОЕ УТОЧНЕНИЕ — инструмент ask_owner(question, context).
Это связь с Арменом в Telegram во время текущего звонка, не просьба перезвонить.
Используй при любом вопросе, где нужно именно решение или неизвестные тебе сведения
Армена: выбор варианта, перенос даты, изменение адреса, замена услуги или товара,
непредусмотренное условие, разрешение выйти за пределы поручения. Это не только бронь.
Если собеседник предлагает два или несколько вариантов, а ПОРУЧЕНИЕ явно не задаёт
выбор, не выбирай ни один вариант самостоятельно: сразу вызови ask_owner. Передай
в options короткие названия всех предложенных вариантов в том же смысле и порядке.
options формируются под конкретную ситуацию, а не из фиксированного списка кнопок.
Не придумывай ответ Армена. Факты, которые знает собеседник, сначала спроси у него;
не отправляй Армену каждую обычную реплику. Не поднимай лишние темы самостоятельно.

question: один конкретный вопрос. Назови, с кем говоришь, и точное предлагаемое
действие; для выбора «Да» должно быть понятно, на что именно даётся согласие.
context: короткие известные факты, исходное поручение и причина уточнения.
Если нужен свободный ответ (например, адрес), попроси нажать «Другое» и написать
его. «Да» само по себе не даёт отсутствующий адрес/дату/другие сведения.
Инструмент сам произнесёт «Секундочку, сейчас уточню» и отправит кнопки; не повторяй
эту фразу вместо вызова инструмента. Действительно вызови ask_owner в этом же ходе.
Не раскрывай секреты, реквизиты или коды. Не проси одобрять неопределённые суммы.

Пока инструмент ждёт, не завершай звонок и не подтверждай ничего за Армена.
Вернувшийся JSON содержит action, question, context, response и instruction:
approve — согласие только на описанное в question действие и указанные условия;
decline — отказ только от предложенного варианта, без автоматического согласия на другой;
instruct — новая инструкция Армена, выполни её в этом же разговоре, если она ясна;
timeout/delivery_failed/cancelled — согласия нет, не принимай альтернативу;
busy — уже идёт уточнение, не создавай второе и не соглашайся сам.
Если сведений недостаточно даже после ответа, уточни снова, не додумывай.
Изменение цены или обязательств требует явного решения, а не общего «Да» по дате.
Продолжи тот же разговор с результатом. Это правило уточнения применяется ко всем
персонам; представление, язык, ограничения поручения и порядок завершения сохраняются.
'''.strip()


def decision_result(question: str, context: str, response: str, request_id: str = '') -> str:
    action = {'yes': 'approve', 'no': 'decline', 'timeout': 'timeout',
              'delivery_failed': 'delivery_failed', 'cancelled': 'cancelled',
              'busy': 'busy'}.get(response, 'instruct')
    instruction = {
        'approve': 'Армен согласен только на действие и условия из question/context. Не расширяй согласие. Продолжи текущий звонок.',
        'decline': 'Армен отказался от предложенного варианта. Не подтверждай его. Продолжи разговор в пределах поручения.',
        'instruct': 'Выполни новое указание Армена из response в этом же звонке. Не выдумывай недостающие сведения.',
        'timeout': 'Армен не ответил вовремя. Согласия нет. Не подтверждай изменения; вежливо заверши или согласуй обратный звонок.',
        'delivery_failed': 'Сообщение не доставлено. Согласия нет. Скажи, что сейчас уточнить не удалось, не принимай решение за Армена.',
        'cancelled': 'Звонок или запрос завершён. Не применяй поздние решения.',
        'busy': 'Другое уточнение уже ожидает ответа. Не создавай дубликат и не подтверждай изменения.',
    }[action]
    return json.dumps(dict(action=action, question=question, context=context,
                           response=response, request_id=request_id,
                           instruction=instruction), ensure_ascii=False)
